const fs = require('fs');
const path = require('path');

const g = JSON.parse(fs.readFileSync(path.join('packages', 'decision', 'golden', 'cases.json'), 'utf8'));
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
const cfg = g.config;

const out = [];
out.push('-- GENERATED by scripts/gen-parity-sql.cjs from packages/decision/golden/cases.json. Do not edit by hand.');
out.push('-- Run in the Supabase SQL editor. "Success" means the database rules match every TypeScript golden case.');
out.push('do $$');
out.push('declare r text[];');
out.push('begin');
for (const c of g.cases) {
  const i = Object.assign({}, g.base, c.override);
  const exp = c.expected.reasons.length
    ? 'array[' + c.expected.reasons.map(q).join(', ') + ']::text[]'
    : "'{}'::text[]";
  const args = [
    i.found ? 'true' : 'false',
    q(i.batchStatus || 'ok'),
    q(i.expiryDate || '2099-01-01') + '::date',
    q(i.today) + '::date',
    i.scanCount,
    i.distinctDevices,
    i.distinctAreas,
    i.confirmedFakeReports,
    i.openUserReports,
    cfg.flagAtDevices,
    cfg.flagAtAreas,
    cfg.flagAtScans,
    cfg.flagAtReports,
  ];
  out.push('  r := public.decide_reasons(' + args.join(', ') + ');');
  out.push('  assert r = ' + exp + ', ' + q(c.name + ': got ') + " || coalesce(r::text, 'null');");
}
out.push("  raise notice 'parity: all % golden cases match', " + g.cases.length + ';');
out.push('end $$;');

fs.mkdirSync(path.join('supabase', 'tests'), { recursive: true });
fs.writeFileSync(path.join('supabase', 'tests', 'parity.sql'), out.join('\n') + '\n');
console.log('Wrote supabase/tests/parity.sql with ' + g.cases.length + ' cases');